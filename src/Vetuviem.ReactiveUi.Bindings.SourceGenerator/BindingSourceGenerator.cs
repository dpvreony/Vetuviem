using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Vetuviem.ReactiveUi.Bindings.SourceGenerator
{
    [Generator]
    public sealed class BindingSourceGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var trigger = context.AnalyzerConfigOptionsProvider
                .Combine(context.ParseOptionsProvider)
                .Combine(context.MetadataReferencesProvider.Collect())
                .Combine(context.CompilationProvider)
                .Select((tuple, _) =>
                {
                    (
                        (
                            (
                                AnalyzerConfigOptionsProvider analyzerConfigOptionsProvider,
                                ParseOptions parseOptionsProvider),
                            ImmutableArray<MetadataReference> metadataReferencesProvider),
                        Compilation compilationProvider) = tuple;

                    return (analyzerConfigOptionsProvider, parseOptionsProvider, metadataReferencesProvider, compilationProvider);
                });

            context.RegisterImplementationSourceOutput(
                trigger,
                static (productionContext, tuple) => Execute(
                    productionContext,
                    tuple.analyzerConfigOptionsProvider,
                    tuple.parseOptionsProvider,
                    tuple.metadataReferencesProvider,
                    tuple.compilationProvider));
        }

        private static void Execute(SourceProductionContext productionContext, AnalyzerConfigOptionsProvider tupleAnalyzerConfigOptionsProvider, ParseOptions tupleParseOptionsProvider, ImmutableArray<MetadataReference> tupleMetadataReferencesProvider, Compilation compilationProvider)
        {
            var bindingModels = FindDerivedClasses(compilationProvider, "Vetuviem.Core.AbstractEnableViewToViewModelBindings`2");
            var allFound = new List<BindingInvocationInfo>();
            var sb = new StringBuilder();
            foreach (var namedTypeSymbol in bindingModels)
            {
                sb.AppendLine($"// {namedTypeSymbol.Name}");
                var found = ProcessBindingModel(compilationProvider, namedTypeSymbol);
                allFound.AddRange(found);
            }

            // emit debug generated file listing discovered invocations
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("namespace Vetuviem.ReactiveUi.Bindings.Generated");
            sb.AppendLine("{");
            sb.AppendLine("    internal static class DebugDiscoveredBindings");
            sb.AppendLine("    {");
            sb.AppendLine("        internal static readonly string[] Items = new string[]");
            sb.AppendLine("        {");
            foreach (var item in allFound)
            {
                var entry = $"Class={item.ClassName};Invocation={item.InvocationName};File={item.FilePath};Line={item.Line};Col={item.Column};Return={item.ReturnTypeName}";
                sb.Append("            \"").Append(entry.Replace("\"", "\\\"")).AppendLine("\",");
            }
            sb.AppendLine("        }; ");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            productionContext.AddSource("BindingSourceGenerator_Debug.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static IEnumerable<BindingInvocationInfo> ProcessBindingModel(Compilation compilation, INamedTypeSymbol namedTypeSymbol)
        {
            // Find all invocations in the class that return a type that inherits from Vetuviem.Core.AbstractControlBindingModel
            var results = new List<BindingInvocationInfo>();

            var baseBindingModel = compilation.GetTypeByMetadataName("Vetuviem.Core.AbstractControlBindingModel`3");
            if (baseBindingModel == null)
                return results;

            foreach (var decl in namedTypeSymbol.DeclaringSyntaxReferences)
            {
                var syntax = decl.GetSyntax();
                var tree = syntax.SyntaxTree;
                var semanticModel = compilation.GetSemanticModel(tree);

                // find invocation expressions inside the type declaration
                var invocations = syntax.DescendantNodes().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.InvocationExpressionSyntax>();
                foreach (var invocation in invocations)
                {
                    var symbolInfo = semanticModel.GetSymbolInfo(invocation);
                    var methodSymbol = symbolInfo.Symbol as IMethodSymbol;
                    if (methodSymbol == null)
                        continue;

                    var returnType = methodSymbol.ReturnType as INamedTypeSymbol;
                    if (returnType == null)
                        continue;

                    if (InheritsFrom(returnType, baseBindingModel))
                    {
                        // determine location
                        var loc = invocation.GetLocation().GetLineSpan();
                        var path = loc.Path ?? string.Empty;
                        var line = loc.StartLinePosition.Line + 1;
                        var col = loc.StartLinePosition.Character + 1;

                        results.Add(new BindingInvocationInfo(
                            className: namedTypeSymbol.ToDisplayString(),
                            invocationName: methodSymbol.Name,
                            filePath: path,
                            line: line,
                            column: col,
                            returnTypeName: returnType.ToDisplayString()));
                    }
                }
            }

            // distinct by symbol (class + invocation + location)
            return results.GroupBy(r => (r.ClassName, r.InvocationName, r.FilePath, r.Line, r.Column, r.ReturnTypeName)).Select(g => g.First());
        }

        private sealed class BindingInvocationInfo
        {
            public string ClassName { get; }
            public string InvocationName { get; }
            public string FilePath { get; }
            public int Line { get; }
            public int Column { get; }
            public string ReturnTypeName { get; }

            public BindingInvocationInfo(string className, string invocationName, string filePath, int line, int column, string returnTypeName)
            {
                ClassName = className;
                InvocationName = invocationName;
                FilePath = filePath;
                Line = line;
                Column = column;
                ReturnTypeName = returnTypeName;
            }
        }

        // call from Execute(...) with 'Compilation compilation' available
        private static IEnumerable<INamedTypeSymbol> FindDerivedClasses(Compilation compilation, string baseFullMetadataName)
        {
            var assembly = compilation.Assembly;
            var baseType = compilation.GetTypeByMetadataName(baseFullMetadataName);
            if (baseType == null)
                yield break;

            foreach (var type in GetAllTypesDeclaredInNamespace(assembly.GlobalNamespace))
            {
                // only types declared in the primary assembly
                if (!SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, assembly))
                    continue;

                if (type.TypeKind != TypeKind.Class)
                    continue;

                // skip the base itself and abstract classes if you want only concrete implementors
                if (type.IsAbstract)
                    continue;

                if (InheritsFrom(type, baseType))
                    yield return type;
            }
        }

        private static bool InheritsFrom(INamedTypeSymbol type, INamedTypeSymbol baseType)
        {
            for (var t = type; t != null; t = t.BaseType)
            {
                if (SymbolEqualityComparer.Default.Equals(t.OriginalDefinition, baseType.OriginalDefinition))
                    return true;
            }
            return false;
        }

        private static IEnumerable<INamedTypeSymbol> GetAllTypesDeclaredInNamespace(INamespaceSymbol ns)
        {
            foreach (var t in ns.GetTypeMembers())
            {
                foreach (var tt in GetAllNestedTypes(t))
                    yield return tt;
            }

            foreach (var childNs in ns.GetNamespaceMembers())
            {
                foreach (var tt in GetAllTypesDeclaredInNamespace(childNs))
                    yield return tt;
            }
        }

        private static IEnumerable<INamedTypeSymbol> GetAllNestedTypes(INamedTypeSymbol type)
        {
            yield return type;
            foreach (var nested in type.GetTypeMembers())
            {
                foreach (var nt in GetAllNestedTypes(nested))
                    yield return nt;
            }
        }
    }
}
